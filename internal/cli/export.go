package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"

	"github.com/CptPhenomeno/kb/internal/core"
)

func (c *cli) exportCmd() *cobra.Command {
	var out string
	cmd := &cobra.Command{
		Use:   "export",
		Short: "Write a readable markdown view of the board (.kanban/board.md)",
		Args:  args(0, 0),
		RunE: func(*cobra.Command, []string) error {
			return c.with(func(s *Session) error {
				snap, err := s.Service.Board(c.ctx)
				if err != nil {
					return err
				}
				md := renderMarkdown(snap)
				if out == "-" {
					_, err := fmt.Fprint(c.app.Stdout, md)
					return err
				}
				path := out
				if path == "" {
					path = filepath.Join(s.Root, ".kanban", "board.md")
				}
				if err := os.WriteFile(path, []byte(md), 0o644); err != nil {
					return err
				}
				if !c.g.quiet && !c.g.json {
					fmt.Fprintf(c.app.Stdout, "✓ board written to %s\n", path)
				}
				return nil
			})
		},
	}
	cmd.Flags().StringVar(&out, "out", "", "output file (default .kanban/board.md, - for stdout)")
	return cmd
}

// renderMarkdown renders the board deterministically: it depends only on
// the board content, never on the clock, so diffs show real changes.
func renderMarkdown(snap *core.Snapshot) string {
	var b strings.Builder
	b.WriteString("# Board\n\nGenerated by `kb export`: do not edit by hand, run `kb export` again.\n\n## Hierarchy\n\n")
	var walk func(it *core.Item, depth int)
	walk = func(it *core.Item, depth int) {
		fmt.Fprintf(&b, "%s- **%s** %s · %s · %s", strings.Repeat("  ", depth), it.ID, it.Type, it.Status, it.Title)
		var extra []string
		if it.Points != 0 {
			extra = append(extra, fmt.Sprintf("%dpt", it.Points))
		}
		if done, total := core.Progress(snap, it); total > 0 {
			if it.Type.IsParentType() {
				extra = append(extra, fmt.Sprintf("%d/%d done", done, total))
			} else {
				extra = append(extra, fmt.Sprintf("tests %d/%d", done, total))
			}
		}
		if blocked, by := core.Blockers(snap, it.ID); blocked {
			extra = append(extra, "blocked by "+strings.Join(by, ", "))
		}
		if len(extra) > 0 {
			fmt.Fprintf(&b, " (%s)", strings.Join(extra, ", "))
		}
		b.WriteString("\n")
		for _, ch := range snap.Children(it.ID) {
			walk(ch, depth+1)
		}
	}
	for _, it := range snap.Items() {
		if it.Parent == "" {
			walk(it, 0)
		}
	}
	b.WriteString("\n## Columns\n")
	for _, st := range core.Statuses() {
		col := core.Column(snap, st)
		fmt.Fprintf(&b, "\n### %s (%d)\n\n", st.Label(), len(col))
		if len(col) == 0 {
			b.WriteString("_empty_\n")
		}
		for _, it := range col {
			fmt.Fprintf(&b, "- %s %s: %s\n", it.ID, it.Type, it.Title)
		}
	}
	b.WriteString("\n## Relations\n\n")
	if len(snap.Relations) == 0 {
		b.WriteString("_none_\n")
	}
	for _, r := range snap.Relations {
		fmt.Fprintf(&b, "- %s %s %s\n", r.From, r.Kind, r.To)
	}
	return b.String()
}
